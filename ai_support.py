    def __init__(self):
        self.faq = {
            "регистрация": "📝 Чтобы начать, просто напишите /start. Это активирует пробный период.",
            "подписка": "💳 Стоимость подписки — 29.90 BYN/месяц. Напишите /subscribe для реквизитов.",
            "пробный период": "⏳ Пробный период длится 14 дней. Напишите /start, чтобы активировать.",
            "прогноз": "📈 Прогнозы строятся на основе 3 AI-моделей. Нажмите /forecast_usd или /forecast_eur.",
            "точность": "🎯 Точность прогнозов — 68-72% за последние 90 дней. Подробнее в /stats.",
            "банки": "🏦 Лучшие банки для обмена — в /banks. Там указаны адреса отделений.",
            "риск": "⚖️ Риск оценивается от 1 до 10. Чем выше цифра, тем выше риск.",
            "калькулятор": "💰 Напишите /calc 1000 BYN, чтобы рассчитать прибыль.",
            "заработок": "💰 Средняя прибыль с одной сделки — 2-3% за 7-14 дней."
        }

    async def get_response(self, query):
        query_lower = query.lower()
        if any(word in query_lower for word in ["аналитик", "эксперт", "поговорить", "связаться", "человек"]):
            return {"text": "⏳ Я переключаю вас на эксперта. Пожалуйста, подождите...", "escalate": True}
        for key, value in self.faq.items():
            if key in query_lower:
                return {"text": value, "escalate": False}
        if "сегодня" in query_lower or "сейчас" in query_lower:
            day = datetime.now().day
            if 18 <= day <= 22:
                return {"text": "📅 Сейчас налоговый период (20-е числа). Исторически курс USD снижается. Рекомендую покупать после 22-го числа.", "escalate": False}
            return {"text": "📅 Сейчас вне налогового периода. Ориентируйтесь на технический анализ: /forecast_usd", "escalate": False}
        return {"text": "🤔 Попробуйте перефразировать вопрос. Или нажмите /connect, чтобы связаться с экспертом.", "escalate": False}
